// Keyword-based problem detection for the scripted demo. Returns null when the goal is ambiguous,
// which makes the agent ask a clarifying question (as described in the Phase 3 spec).
export function detectScenario(text) {
  const t = text.toLowerCase()
  if (/fraud|anomal|suspicious|abuse|money laundering/.test(t)) return 'fraud'
  if (/churn|cancel|attrition|retain|retention|leave|unsubscribe|renewal|default/.test(t)) return 'churn'
  if (/forecast|demand|next (week|month|quarter|year)|inventory|sales|revenue|volume|traffic|footfall/.test(t)) return 'forecast'
  if (/price|cost|value|estimate|how much|ltv|lifetime|salary|amount|valuation/.test(t)) return 'price'
  return null
}
